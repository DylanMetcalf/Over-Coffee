import json,sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.varLib import instancer
F='/home/user/Over-Coffee/web/assets/fonts/'
def load(name,axes=None):
    f=TTFont(F+name)
    f.flavor=None
    if axes and 'fvar' in f: f=instancer.instantiateVariableFont(f,axes)
    return f
def word(f,text,kern=None):
    gs=f.getGlyphSet(); cmap=f.getBestCmap(); upm=f['head'].unitsPerEm
    x=0; paths=[]; 
    for i,ch in enumerate(text):
        g=cmap[ord(ch)]
        pen=SVGPathPen(gs); tp=TransformPen(pen,(1,0,0,-1,x,0)); gs[g].draw(tp)
        paths.append(pen.getCommands()); x+=gs[g].width+(kern or {}).get(ch,0)
    return ' '.join(paths),x,upm
# Outlines the brand letterforms so the logo never depends on a web font.
# Run: python3 scripts/logo/build-logo.py   (needs: pip install fonttools brotli)
import os
OUT=os.path.join(os.path.dirname(__file__),'..','..','web','js','render','logo-paths.js')
ser=load('instrument-serif-italic.woff2')
bri=load('bricolage-normal.woff2',{'wght':800,'wdth':100,'opsz':96})
def r(p): 
    import re
    return re.sub(r'(\d+\.\d)\d*',lambda m:m.group(1),p)
items={
 'OVER':word(ser,'over'),'COFFEE':word(bri,'coffee'),'DOT':word(bri,'.'),'C':word(ser,'c'),'OC':word(ser,'oc')}
with open(OUT,'w') as f:
    f.write('// GENERATED by scripts/logo/build-logo.py. Outlined letterforms for the Over Coffee logo.\n')
    f.write('// OVER, C, OC: Instrument Serif Italic. COFFEE, DOT: Bricolage Grotesque ExtraBold. (SIL OFL)\n')
    for k,(p,w,u) in items.items():
        f.write(f"export const {k}_PATH = '{r(p)}';\nexport const {k}_W = {round(w)};\n")
print('wrote',OUT)
